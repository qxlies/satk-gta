_KIND_PREFIX = {"bike", "boat", "flying", "gun", "melee", "aim", "car", "peds", "pedstats"}


def out_dir(name: str) -> Path:
    """``<work>/out/addon/<name>`` (a plain folder name; paths are refused)."""
    if not re.fullmatch(r"[A-Za-z0-9_.-]{1,64}", name) or set(name) == {"."}:
        raise SatkError("BAD_PARAMS", f"bad output name {name!r}", hint="use letters, digits, '_', '-' and '.'")
    return ensure_writable(Path(os.path.abspath(cfg().paths.work)) / "out" / "addon" / name)


def readme_header(title: str) -> list[str]:
    """Comment lines that start a generated Mod Loader readme (``#`` lines are never read as data)."""
    return [f"# {title}", "# Generated by satk. Mod Loader reads the data lines of this file (its readme feature);",
            "# lines starting with # are comments.", ""]


def _split_kind(name: str, allowed: tuple[str, ...]) -> tuple[str | None, str]:
    head, dot, rest = name.partition(".")
    if dot and head.lower() in _KIND_PREFIX and head.lower() in allowed:
        return head.lower(), rest
    return None, name


# --------------------------------------------------------------------------- key resolution


def resolve_handling(gd: GameData, key: str) -> tuple[str, list]:
    """Handling id and the models using it from ``handling:ID``, ``model:411``, ``411``, a model or handling name."""
    rel, hf = gd.handling
    k = key.strip()
    if k.lower().startswith("handling:"):
        hid = k.split(":", 1)[1]
    elif k.lower().startswith("model:") or re.fullmatch(r"\d+", k) or k.lower() in gd.base.by_name:
        m = gd.model(k)
        if m.sec != "cars" or not m.handling:
            raise SatkError("BAD_PARAMS", f"model:{m.id} {m.name} is not a vehicle",
                            hint="give a vehicle model or a handling id")
        hid = m.handling
    else:
        hid = k
    rec = hf.get(hid)
    if rec is None:
        ids = hf.ids()
        close = difflib.get_close_matches(hid.upper(), [i.upper() for i in ids], n=3, cutoff=0.6)
        close += difflib.get_close_matches(hid.lower(), [n for n, m in gd.base.by_name.items() if m.sec == "cars"],
                                           n=3, cutoff=0.7)
        raise SatkError("NOT_FOUND", f"no handling record {hid!r} in {rel}", hint="satk data get handling infernus",
                        did_you_mean=close)
    return rec.hid, gd.models_of_handling(rec.hid)


def resolve_weapon(gd: GameData, key: str) -> tuple[str, list[W.WRec]]:
    """``(label, lines)`` for ``PISTOL``, ``weapon:22``, ``22``, ``model:346``, ``colt45`` or ``aim:colt45``."""
    _rel, wf = gd.weapons
    k = key.strip()
    if k.lower().startswith("aim:"):
        r = wf.aim(k[4:])
        if r is None:
            raise SatkError("NOT_FOUND", f"no aim line for anim group {k[4:]!r}",
                            did_you_mean=[f"aim:{x[1].lower()}" for x in wf.recs if x[0] == "aim"][:5])
        return f"aim:{r.name}", [r]
    name = None
    if k.lower().startswith("weapon:") and not k[7:].strip().isdigit():
        k = k[7:].strip()
    if k.lower().startswith("weapon:") or (re.fullmatch(r"\d+", k) and int(k) < 100):
        wid = int(k.split(":", 1)[-1])
        name = next((n for n, i in F.table("weapon")["types"].items() if i == wid), None)
        if name is None:
            raise SatkError("NOT_FOUND", f"no weapon type {wid}", hint="weapon ids are 0-46 (satk data explain weapon)")
    elif wf.by_type(k):
        name = k.upper()
    else:
        try:
            m = gd.model(k, "weapon")
        except SatkError:
            close = difflib.get_close_matches(k.upper(), wf.types(), n=3, cutoff=0.6)
            raise SatkError("NOT_FOUND", f"no weapon type or weapon model {key!r}",
                            hint="satk data get weapon PISTOL", did_you_mean=close) from None
        hits = sorted({r.name.upper() for r in wf.recs.values() if r.kind != "aim"
                       and m.id in (r.values.get("model1"), r.values.get("model2"))})
        if not hits:
            raise SatkError("NOT_FOUND", f"no weapon.dat line uses model:{m.id} {m.name}")
        if len(hits) > 1:
            raise SatkError("AMBIGUOUS", f"model:{m.id} {m.name} is used by {', '.join(hits)}",
                            hint=f"satk data get weapon {hits[0]}", did_you_mean=hits)
        name = hits[0]
    recs = wf.by_type(name)
    if not recs:
        raise SatkError("NOT_FOUND", f"weapon type {name} has no line in weapon.dat")
    return name, recs


# --------------------------------------------------------------------------- get


def _num(v):
    if isinstance(v, float):
        return round(v, 6)
    return v


def _rows_handling(rec: H.HRec, wanted: set[tuple[str, str]] | None) -> list[list]:
    rows = []
    for f in H.field_table(rec.kind):
        if wanted is not None and (rec.kind, f["key"]) not in wanted:
            continue
        v = rec.values[f["key"]]
        shown = rec.token(f["key"]) if f["type"] == "x" else _num(v)
        label = f["name"] if rec.kind == "car" else f"{rec.kind}.{f['name']}"
        row = [label, shown, H.value_note(rec.kind, f, v)]
        if wanted is not None:
            row.append(f["desc"])
        rows.append(row)
    return rows


def _wanted(file: str, names: list[str] | None, present: tuple[str, ...]) -> set[tuple[str, str]] | None:
    if not names:
        return None
    out = set()
    for n in names:
        kind, bare = _split_kind(n, present)
        if kind is not None:
            k, f = F.find_field(file, bare, kind)
        else:
            k = None
            for kk in present:
                try:
                    k, f = F.find_field(file, bare, kk)
                    break
                except SatkError:
                    continue
            if k is None:
                F.find_field(file, bare)          # raises NOT_FOUND with suggestions
                raise SatkError("NOT_FOUND", f"{n!r} is not a field of the lines this record has",
                                data={"kinds": list(present)})
        out.add((k, f["key"]))
    return out


def get(file: str, key: str, field: list[str] | None = None, profile: str = "vanilla", limit: int = 60,
        cursor: str | None = None) -> dict:
    gd = GameData(profile)
    lim = clamp_limit(limit, default=60)
    off = int(cursor) if cursor and cursor.isdigit() else 0
    extra: dict = {}
    if file == "handling":
        hid, models = resolve_handling(gd, key)
        rel, hf = gd.handling
        recs = hf.kinds_of(hid)
        wanted = _wanted("handling", field, tuple(r.kind for r in recs))
        rows = [row for r in recs for row in _rows_handling(r, wanted)]
        cols = ["field", "value", "unit"] + (["meaning"] if wanted is not None else [])
        extra = {"id": f"handling:{hid}", "file": rel, "lines": [r.line for r in recs],
                 "kinds": [r.kind for r in recs], "models": [f"model:{m.id} {m.name}" for m in models]}
        if not models:
            extra["hint"] = "no vehicles.ide line of this profile uses this handling id"
    elif file == "weapon":
        label, recs = resolve_weapon(gd, key)
        rel, _wf = gd.weapons
        cols, rows = _rows_weapon(recs, field)
        extra = {"id": label if label.startswith("aim:") else f"weapon:{label}", "file": rel,
                 "lines": [r.line for r in recs], "kind": recs[0].kind}
        if recs[0].kind == "gun":
            wid = W.type_id(recs[0].name)
            if wid is not None:
                extra["weapon_id"] = wid
    elif file == "carcols":
        cols, rows, extra = _carcols(gd, key)
    elif file == "peds":
        cols, rows, extra = _peds(gd, key, field)
    else:  # pragma: no cover - Literal in the op
        raise SatkError("BAD_PARAMS", f"unknown data file {file!r}")
    page = rows[off:off + lim]
    env = table(cols, page, total=len(rows), next=str(off + lim) if off + lim < len(rows) else None)
    for k, v in extra.items():
        if v not in (None, [], {}, ""):
            env[k] = v
    return env


def _rows_weapon(recs: list[W.WRec], names: list[str] | None) -> tuple[list[str], list[list]]:
    kind = recs[0].kind
    flist = F.table("weapon")[kind]
    wanted = None
    if names:
        wanted = {F.find_field("weapon", _split_kind(n, (kind,))[1], kind)[1]["key"] for n in names}
    skills = F.table("weapon")["skills"]
    multi = kind == "gun" and len(recs) > 1
    heads = [skills.get(str(r.skill), str(r.skill)) for r in recs] if multi else ["value"]
    cols = ["field"] + heads + ["unit"] + (["meaning"] if wanted else [])
    rows = []
    for f in flist:
        if wanted is not None and f["key"] not in wanted:
            continue
        if f["key"] == "type" or (f["key"] == "skill" and multi) or (kind == "aim" and f["key"] == "anim_group"):
            continue
        vals = []
        for r in recs if multi else recs[:1]:
            if f["key"] not in r.values:
                vals.append("-")
                continue
            v = r.values[f["key"]]
            i = r.first + [x["key"] for x in flist].index(f["key"])
            vals.append(r.tl.get(i) if f["type"] == "x" else _num(v))
        if all(v == "-" for v in vals):
            continue
        ref = next((r.values[f["key"]] for r in recs if f["key"] in r.values), None)
        note = W.value_note(f, ref) if ref is not None else f.get("unit", "")
        if f.get("flags") and multi:
            note = _flag_diff(recs, f, flist)
        row = [f["name"]] + vals + [note]
        if wanted is not None:
            row.append(f["desc"])
        rows.append(row)
    return cols, rows


def _flag_diff(recs: list[W.WRec], f: dict, flist: list[dict]) -> str:
    """Decoded flags of the first line, then what each other skill line adds (+) or lacks (-)."""
    skills = F.table("weapon")["skills"]
    base = F.flag_names("weapon", f["flags"], int(recs[0].values[f["key"]]))
    parts = ["|".join(base) or "none"]
    for r in recs[1:]:
        cur = F.flag_names("weapon", f["flags"], int(r.values[f["key"]]))
        d = [f"+{n}" for n in cur if n not in base] + [f"-{n}" for n in base if n not in cur]
        if d:
            parts.append(f"{skills.get(str(r.skill), r.skill)}: {' '.join(d)}")
    return "; ".join(parts)


def _typed(text: str, typ: str):
    """A file token as a JSON number when it is an int/float field (hex and words stay text)."""
    try:
        if typ == "i":
            return int(text)
        if typ == "f":
            return float(text)
    except ValueError:
        pass
    return text


def _carcols(gd: GameData, key: str) -> tuple[list[str], list[list], dict]:
    m = gd.model(key, "vehicle")
    rel, cc, _text = gd.carcols
    if cc is None:
        raise SatkError("NOT_FOUND", f"profile {gd.profile!r} has no data/carcols.dat")
    entry = cc.cars.get(m.name.lower())
    if entry is None:
        raise SatkError("NOT_FOUND", f"carcols.dat has no colours for {m.name}",
                        hint="the game then uses colour 0 (black) and 0; add a 'car' line")
    pal = cc.palette
    rows = []
    for i, s in enumerate(entry.sets):
        rgb = [pal[c].hex if 0 <= c < len(pal) else "?" for c in s]
        names = [(pal[c].name or "") if 0 <= c < len(pal) else "?" for c in s]
        rows.append([i, ",".join(map(str, s)), " ".join(rgb), ", ".join(names)])
    return ["set", "colors", "rgb", "names"], rows, {"id": f"carcols:{m.name}", "file": rel, "line": entry.line,
                                                      "section": "car4" if entry.four else "car",
                                                      "model": f"model:{m.id}"}


def _peds(gd: GameData, key: str, names: list[str] | None) -> tuple[list[str], list[list], dict]:
    m = gd.model(key, "ped")
    ml = gd.model_line(m)
    t = F.table("peds")
    raw = [tok for tok in ml.text.split("#", 1)[0].replace(",", " ").split()]
    wanted = None
    if names:
        wanted = set()
        for n in names:
            kind, bare = _split_kind(n, ("peds", "pedstats"))
            wanted.add(F.find_field("peds", bare, kind)[1]["key"])
    rows = []
    for f, v in zip(t["peds"], raw):
        if wanted is not None and f["key"] not in wanted:
            continue
        note = f.get("unit", "")
        if f["key"] == "cars_mask":
            try:
                names_ = F.flag_names("peds", "car_groups", int(v, 16))
                note = "|".join(names_) if names_ else "none"
            except ValueError:
                pass
        rows.append([f["name"], _typed(v, f["type"]), note] + ([f["desc"]] if wanted is not None else []))
    stat_name = str(ml.rec.extra.get("stat", ""))
    ps = gd.pedstats
    extra = {"id": f"model:{m.id}", "name": m.name, "file": ml.ide, "line": ml.line}
    if ps is not None:
        hit = next((s for s in ps[1] if s.name.lower() == stat_name.lower()), None)
        if hit is not None:
            extra["pedstats"] = f"{ps[0]}:{hit.line}"
            for f, v in zip(t["pedstats"][1:], hit.values):
                if wanted is not None and f["key"] not in wanted:
                    continue
                rows.append([f"pedstats.{f['key']}", _typed(v, f["type"]), f.get("unit", "")]
                            + ([f["desc"]] if wanted is not None else []))
    return ["field", "value", "unit"] + (["meaning"] if wanted is not None else []), rows, extra


