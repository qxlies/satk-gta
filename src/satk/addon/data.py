"""``satk data get|patch|explain``: read, change and explain records of the game's data files.

* ``get``: one record with every field, its value and unit (``handling``, ``carcols``, ``peds``, ``weapon``);
* ``patch``: new values for ``handling.cfg`` or ``weapon.dat`` fields, written as a Mod Loader folder with only
  the changed lines (readme lines, merged by Mod Loader), an MTA Lua snippet, or a full patched copy of the file;
* ``explain``: what a field (or a flag bit) means, its unit and range.

Records are read from the profile root (read-only); outputs go to ``<work>/out/addon/<name>/``.
Stdlib only.
"""

