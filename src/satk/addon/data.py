def explain(file: str, field: str | None = None, limit: int = 20, cursor: str | None = None) -> dict:
    t = F.table(file)
    if field is None:
        rows = []
        for kind in F.kinds(file):
            for f in t[kind]:
                name = f.get("name", f["key"])
                label = name if kind in ("car", "gun", "peds") else f"{kind}.{name}"
                rows.append([label, f.get("col", ""), f.get("unit", ""), f["desc"]])
        lim = clamp_limit(limit)
        off = int(cursor) if cursor and cursor.isdigit() else 0
        env = table(["field", "col", "unit", "meaning"], rows[off:off + lim], total=len(rows),
                    next=str(off + lim) if off + lim < len(rows) else None)
        env["hint"] = f"satk data explain {file} <field> (one field with type, range and MTA name)"
        return env
    flag = _flag_bit(file, field)
    if flag is not None:
        return obj(id=f"{file}.{flag[0]}.{flag[1]['name']}", file=file, flags=flag[0], bit=flag[1]["bit"],
                   value=f"0x{1 << flag[1]['bit']:X}", meaning=flag[1].get("desc"))
    allowed = F.kinds(file)
    kind, bare = _split_kind(field, allowed)
    k, f = F.find_field(file, bare, kind)
    env = obj(id=f"{file}.{f.get('name', f['key'])}", file=file, kind=k, key=f["key"], name=f.get("name"),
              col=f.get("col"), type={"f": "float", "i": "int", "x": "hex", "c": "letter", "s": "word"}[f["type"]],
              unit=f.get("unit"), range=f.get("range"), choices=f.get("choices"), meaning=f["desc"],
              aliases=f.get("aliases"))
    if f.get("mta"):
        env["mta"] = f["mta"] if f.get("mta_set", True) else f"{f['mta']} (read-only in MTA)"
        if f.get("mta_scale"):
            env["mta_unit"] = "seconds (file frames / 30)"
    if f.get("flags"):
        env["bits"] = [[f"0x{1 << b['bit']:X}", b["name"], b.get("desc", "")] for b in F.flag_bits(file, f["flags"])]
    if f.get("enum"):
        enum = t.get("enums", {}).get(f["enum"])
        if enum:
            env["values"] = enum
    if file == "handling" and k == "car" and f["key"] in ("drive", "engine"):
        env["values"] = t["enums"][f["key"]]
    if file == "handling":
        env["prefix"] = t["kinds"][k]["prefix"] or "(none)"
    return env


def _flag_bit(file: str, name: str) -> tuple[str, dict] | None:
    t = F.table(file)
    groups = {"handling": ("model_flags", "handling_flags"), "weapon": ("flags",), "peds": ("car_groups",)}[file]
    for g in groups:
        for b in t[g]:
            if b["name"].lower() == name.strip().lower():
                return g, b
    return None


# --------------------------------------------------------------------------- patch


def _parse_sets(sets: list[str]) -> list[tuple[str, str]]:
    out = []
    for s in sets:
        k, eq, v = s.partition("=")
        if not eq or not k.strip() or not v.strip():
            raise SatkError("BAD_PARAMS", f"bad change {s!r}", hint="write field=value, e.g. fMass=1500")
        out.append((k.strip(), v.strip()))
    if not out:
        raise SatkError("BAD_PARAMS", "no changes given", hint="satk data patch handling infernus fMass=1500")
    return out


def _check(file: str, f: dict, text: str):
    if file == "handling":
        return H.check_value(f, text)
    t = text.strip()
    if f["type"] == "x" and t.lower().startswith("0x"):
        t = t[2:]
    from .tokline import parse_typed

    try:
        v = parse_typed(t, f["type"])
    except ValueError as e:
        raise SatkError("BAD_PARAMS", f"{f['name']}: {e}", hint=f"satk data explain weapon {f['name']}") from None
    if "choices" in f and (v.upper() if isinstance(v, str) else v) not in f["choices"]:
        raise SatkError("BAD_PARAMS", f"{f['name']} must be one of {', '.join(map(str, f['choices']))}")
    if isinstance(v, str):
        v = v.upper() if f["key"] in ("fire_type", "base_combo") else v
    return v, None


def patch(file: str, key: str, sets: list[str], target: str = "modloader", profile: str = "vanilla",
          name: str | None = None, skill: str = "all", dry_run: bool = False) -> dict:
    gd = GameData(profile)
    pairs = _parse_sets(sets)
    warn: list[str] = []
    rows: list[list] = []
    old_new: list[tuple] = []          # (old rec, new rec, {key: new value})
    if file == "handling":
        hid, models = resolve_handling(gd, key)
        rel, hf = gd.handling
        recs = {r.kind: r for r in hf.kinds_of(hid)}
        by_kind: dict[str, dict] = {}
        for fname, text in pairs:
            kind, bare = _split_kind(fname, tuple(recs))
            hits = []
            for kk in ([kind] if kind else list(recs)):
                try:
                    hits.append((kk,) + F.find_field("handling", bare, kk))
                except SatkError:
                    pass
            if not hits:
                F.find_field("handling", bare)       # raises NOT_FOUND with suggestions
                raise SatkError("BAD_PARAMS", f"{fname}: {hid} has no line with this field", data={"lines": list(recs)},
                                hint="bike/boat/flying fields need the vehicle's '!', '%' or '$' line")
            if len(hits) > 1:
                raise SatkError("AMBIGUOUS", f"{fname} exists in the {' and '.join(h[0] for h in hits)} lines",
                                hint=f"prefix it: {hits[0][0]}.{bare}",
                                did_you_mean=[f"{h[0]}.{bare}" for h in hits])
            kk, _k, f = hits[0]
            v, w = _check("handling", f, text)
            if w:
                warn.append(w)
            by_kind.setdefault(kk, {})[f["key"]] = (v, text)
        for kk, ch in by_kind.items():
            old = recs[kk]
            new = old.patched(ch)
            old_new.append((old, new, {k2: v for k2, (v, _t) in ch.items()}))
            for k2, (v, _t) in ch.items():
                f = next(x for x in H.field_table(kk) if x["key"] == k2)
                label = f["name"] if kk == "car" else f"{kk}.{f['name']}"
                rows.append([label, old.token(k2), new.token(k2)])
        ident = f"handling:{hid}"
        default_name = f"{hid.lower()}-handling-{target}"
    elif file == "weapon":
        label, recs = resolve_weapon(gd, key)
        rel, wf = gd.weapons
        sel = _skill_filter(recs, skill)
        flist = F.table("weapon")[recs[0].kind]
        changes = {}
        for fname, text in pairs:
            _k, f = F.find_field("weapon", _split_kind(fname, (recs[0].kind,))[1], recs[0].kind)
            if f["key"] in ("type",):
                raise SatkError("BAD_PARAMS", "the weapon type name cannot be patched", hint="patch the other fields")
            v, _w = _check("weapon", f, text)
            changes[f["key"]] = (v, text)
        for r in sel:
            new = r.patched(changes)
            old_new.append((r, new, {k2: v for k2, (v, _t) in changes.items()}))
            for k2 in changes:
                i = r.first + [x["key"] for x in flist].index(k2)
                lab = next(x["name"] for x in flist if x["key"] == k2)
                if r.skill is not None and len(sel) > 1:
                    lab = f"{lab}[{F.table('weapon')['skills'].get(str(r.skill), r.skill)}]"
                rows.append([lab, r.tl.get(i), new.tl.get(i)])
        ident = label if label.startswith("aim:") else f"weapon:{label}"
        default_name = f"{label.replace(':', '-').lower()}-weapon-{target}"
    else:  # pragma: no cover
        raise SatkError("BAD_PARAMS", f"patch supports handling and weapon, not {file!r}")
    folder = out_dir(name or default_name)
    files: list[str] = []
    lua: list[str] = []
    if target == "modloader":
        body, fallback = _modloader(file, old_new, ident)
        if fallback:
            warn.append(f"{fallback}: wrote a full data/{Path(rel).name} copy instead")
            payload = {f"data/{Path(rel).name}": _full(file, gd, old_new)}
        else:
            payload = {f"{(name or default_name)}.txt": body}
    elif target == "full":
        payload = {f"data/{Path(rel).name}": _full(file, gd, old_new)}
    else:
        if file == "handling":
            for old, _new, ch in old_new:
                calls, w = H.mta_calls(old, ch, [(m.id, m.name) for m in models])
                lua += calls
                warn += w
            if not models:
                warn.append(f"NO_MODELS: no vehicle of profile {profile!r} uses handling id {hid}")
        else:
            for old, _new, ch in old_new:
                calls, w = W.mta_calls(old, ch)
                lua += calls
                warn += w
        head = [f"-- {ident}: generated by satk data patch (server side; applies to every vehicle/ped of the model)"]
        if file == "weapon":
            head.append("-- animation frames of weapon.dat are converted to seconds (frames / 30)")
        payload = {f"{file}.lua": "\n".join(head + lua) + "\n"}
    for rel_out, data in sorted(payload.items()):
        dst = folder.joinpath(*rel_out.split("/"))
        if not dry_run:
            atomic_write(dst, data if isinstance(data, bytes) else data.encode("latin-1", errors="replace"))
        files.append(rel_out)
    env = table(["field", "old", "new"], rows, warn=list(dict.fromkeys(warn)))
    env.update({"id": ident, "target": target, "file": rel, "out": jpath(folder), "files": files,
                "old": [o.text for o, _n, _c in old_new], "new": [n.text for _o, n, _c in old_new]})
    if lua:
        env["lua"] = lua[:20]
    if dry_run:
        env["dry_run"] = True
    if target == "modloader" and not dry_run:
        env["hint"] = (f"check: satk mod inspect {jpath(folder)} --profile {profile}; "
                       "install: copy the folder into <game>/modloader/")
    return env


def _skill_filter(recs: list[W.WRec], skill: str) -> list[W.WRec]:
    if recs[0].kind != "gun" or skill == "all":
        return recs
    names = {v: int(k) for k, v in F.table("weapon")["skills"].items()}
    want = int(skill) if skill.isdigit() else names.get(skill.lower())
    if want is None:
        raise SatkError("BAD_PARAMS", f"bad skill {skill!r}", hint="--skill all|poor|std|pro|cop (or 0-3)")
    sel = [r for r in recs if r.skill == want]
    if not sel:
        raise SatkError("NOT_FOUND", f"{recs[0].name} has no skill {skill} line",
                        data={"skills": [r.skill for r in recs]})
    return sel


def _modloader(file: str, old_new: list, ident: str) -> tuple[str, str | None]:
    """Readme text with the changed lines, or ``("", why)`` when Mod Loader would not read one of them."""
    from ..modinspect.traits import HandlingTrait, trim_config_line
    from .add import readme_weapon_ok

    if file == "weapon" and any(o.kind == "aim" for o, _n, _c in old_new):
        return "", "README_UNSUPPORTED: Mod Loader reads no aim ('%') lines from readmes"
    for _o, n, _c in old_new:
        if file == "weapon":
            ok = readme_weapon_ok(n.text)
        else:
            ok = HandlingTrait().readme_rec(trim_config_line(n.text), 0, frozenset()) is not None
        if not ok:
            return "", f"README_FALLBACK: Mod Loader would not read line {n.line} from a readme"
    lines = readme_header(f"{ident}: changed {'handling.cfg' if file == 'handling' else 'weapon.dat'} lines")
    lines += [n.text for _o, n, _c in old_new]
    return "\r\n".join(lines) + "\r\n", None


def _full(file: str, gd: GameData, old_new: list) -> bytes:
    hf = gd.handling[1] if file == "handling" else gd.weapons[1]
    return hf.render({o.line: n.text for o, n, _c in old_new}).encode("latin-1")
