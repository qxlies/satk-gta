def _rows(ch: str) -> list[str]:
    g = _GLYPHS.get(ch) or _GLYPHS.get(ch.upper()) or _GLYPHS["?"]
    return g.split(" ")


def has_glyph(ch: str) -> bool:
    """True if ``ch`` (or its uppercase form) has its own glyph."""
    return ch in _GLYPHS or ch.upper() in _GLYPHS


def text_size(text: str, scale: int = 1) -> tuple[int, int]:
    """Pixel size ``(w, h)`` of ``text`` (one line) at an integer ``scale``."""
    s = max(1, int(scale))
    n = len(text)
    if n == 0:
        return 0, GLYPH_H * s
    return (n * ADVANCE - 1) * s, GLYPH_H * s


@lru_cache(maxsize=1024)
def text_mask(text: str, scale: int = 1) -> tuple[int, int, bytes]:
    """Render one line: ``(w, h, mask)``; ``mask`` is ``w*h`` bytes, 255 = ink, 0 = empty."""
    s = max(1, int(scale))
    w, h = text_size(text, s)
    if w == 0:
        return 0, h, b""
    buf = bytearray(w * h)
    ink = b"\xff" * s
    for ci, ch in enumerate(text):
        x0 = ci * ADVANCE * s
        for ry, row in enumerate(_rows(ch)):
            for rx, c in enumerate(row):
                if c != "#":
                    continue
                for dy in range(s):
                    o = (ry * s + dy) * w + x0 + rx * s
                    buf[o:o + s] = ink
    return w, h, bytes(buf)
