"""A tiny built-in 5x7 bitmap font for numbers and captions on sheets and maps (stdlib only).

Why not a TrueType font: the output must be byte-identical on every machine and with or
without Pillow (SPEC §3.6), and numbers must be crisp at small sizes. Lowercase letters are
drawn with the uppercase glyphs (except ``m`` for metres); unknown characters become ``?``.

Example::

    w, h, mask = text_mask("16", scale=2)   # mask: bytes of w*h, 255 = ink, 0 = background
"""

