_START_ORDER = (R.CONTENT, R.LOGIC)


def ingame_dir() -> Path:
    return paths.work("mta", "ingame")


def state_path() -> Path:
    return ingame_dir() / "state.json"


def load_state() -> dict[str, Any]:
    try:
        d = json.loads(state_path().read_text(encoding="utf-8"))
        return d if isinstance(d, dict) else {}
    except (OSError, ValueError):
        return {}


def save_state(d: dict[str, Any]) -> Path:
    return paths.atomic_write(state_path(), json.dumps(d, indent=1, sort_keys=True, ensure_ascii=False) + "\n")


def resources_dir() -> Path:
    from ..viewer.backends import mta_lua

    return mta_lua.server_root() / "mods" / "deathmatch" / "resources"


# --------------------------------------------------------------------------- client preflight


def preflight() -> dict[str, Any]:
    """Read-only: is the one-time admin setup done, is a game already running, can ``play`` start one."""
    from ..viewer.backends import mta_lua

    pre = mta_lua.client_preflight()
    state = {c[0]: c[1] for c in pre["checks"]}
    setup = [k for k in state if k != "gta_not_running"]
    out: dict[str, Any] = {"ready": bool(pre["ready"]), "setup_done": all(state[k] == "ok" for k in setup),
                           "game_running": state.get("gta_not_running") == "blocker"}
    if pre["blockers"]:
        out["blockers"] = pre["blockers"]
    return out


def _ps1(lines: list[str]) -> bytes:
    # PowerShell 5.1 reads BOM-less UTF-8 as the ANSI code page: write a BOM, CRLF line ends
    return ("﻿" + "\r\n".join(lines) + "\r\n").encode("utf-8")


