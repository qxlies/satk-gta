"""The test server, its state, the client preflight and the bridge to the game.

The server is the private loopback server of the ``game`` target (:mod:`satk.viewer.backends.mta_lua`,
``<work>/mta/server``) with two more startup resources (``satk-testdrive``, ``satk-testdrive-mod``), so
``satk view ... --target game`` keeps working on the same server. :class:`Bridge` talks to the
resources through the ``satk-agent`` rpc (``lua.exec`` on the server or the client, calling the
exports ``td``/``tdc``) and takes frames with the agent's ``capture``. satk never starts the MTA
client here: :func:`write_scripts` writes ``play.cmd`` and the one-time ``admin-setup.ps1`` /
``admin-rollback.ps1`` for the user under ``<work>/mta/ingame``.
"""

