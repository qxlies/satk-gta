def play_info(port: int, scripts: dict[str, str] | None = None) -> dict[str, Any]:
    url = f"mtasa://127.0.0.1:{port}"
    out = {"url": url, "command": "satk ingame play", "console": f"connect 127.0.0.1 {port}"}
    if scripts:
        out["file"] = scripts.get("play")
        out["client"] = f"\"{scripts.get('client_exe')}\" {url}"
    return out


# --------------------------------------------------------------------------- bridge


def _lit(v: Any) -> str:
    return R.lua(v if v is not None else {})


class Bridge:
    """``td``/``tdc`` calls and frames through the satk-agent rpc of the ``game`` endpoint."""

    def __init__(self, backend=None):
        if backend is None:
            from ..viewer.backends.mta_lua import MtaLuaBackend

            backend = MtaLuaBackend.from_discovery("game", "game")
        self.b = backend

    def exec(self, code: str, side: str = "server", timeout_ms: int = 8000) -> list:
        r = self.b.call("lua.exec", {"code": code, "side": side, "timeout_ms": timeout_ms})
        err = r.get("error") if isinstance(r, dict) else None
        if err:
            where = f" ({err.get('file')}:{err.get('line')})" if err.get("file") else ""
            raise SatkError("EXTERNAL_TOOL", f"Lua error on the {side}: {err.get('msg')}{where}")
        return list(r.get("values") or []) if isinstance(r, dict) else []

    def _call(self, side: str, fn: str, cmd: str, args: dict | None) -> Any:
        # the client knows only running resources; the server also knows stopped ones (getResourceState)
        code = (f"local r = getResourceFromName({R.lua(R.LOGIC)}) "
                "if not r or (getResourceState and getResourceState(r) ~= 'running') then "
                f"return {{error = {R.lua(R.LOGIC + ' is not running')}, not_running = true}} end "
                f"return call(r, {R.lua(fn)}, {R.lua(cmd)}, {_lit(args)})")
        vals = self.exec(code, side)
        out = vals[0] if vals else None
        if isinstance(out, dict) and out.get("not_running"):
            raise SatkError("NOT_READY", f"{R.LOGIC} is not running on the {side}",
                            hint="satk ingame start" if side == "server" else
                            "the client has not loaded the resources yet: wait, or reconnect")
        if out is None or out is False:
            raise SatkError("NOT_READY", f"{R.LOGIC} did not answer {cmd!r} on the {side}")
        if isinstance(out, dict) and out.get("error"):
            raise SatkError("EXTERNAL_TOOL", f"{R.LOGIC} {cmd}: {out['error']}")
        return out

    def server(self, cmd: str, args: dict | None = None) -> Any:
        return self._call("server", "td", cmd, args)

    def client(self, cmd: str, args: dict | None = None) -> Any:
        return self._call("client", "tdc", cmd, args)

    def hello(self) -> dict:
        self.b._hello = None
        return self.b.call("hello", {})

    def client_joined(self) -> bool:
        return bool((self.hello().get("mta") or {}).get("client"))

    def capture(self, pose: dict | None, prefix: Path, *, w: int, h: int, settle: int | None = None) -> dict:
        params: dict[str, Any] = {"path_prefix": str(prefix).replace("\\", "/"), "w": int(w), "h": int(h)}
        if pose:
            params["pose"] = pose
        if settle is not None:
            params["settle"] = {"max_frames": max(0, min(1200, int(settle)))}
        return self.b.call("capture", params)

    def log_poll(self, since: int = 0, max_items: int = 500) -> dict:
        return self.b.call("log.poll", {"since": int(since), "max": int(max_items)})


