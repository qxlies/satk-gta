def ensure_server(port: int, httpport: int, timeout: float) -> tuple[dict, list[str]]:
    """Start the loopback server with the test resources, or reuse the running ``game`` server."""
    from ..viewer.backends import mta_lua

    warn: list[str] = []
    st = mta_lua.status(probe=True)
    if st.get("up"):
        st["reused"] = True
        return st, warn
    p, hp = port, httpport
    if not mta_lua.loopback_port_free(p, udp=True) or not mta_lua.loopback_port_free(hp):
        p, hp = None, None
        warn.append(f"PORT_BUSY: 127.0.0.1:{port}/{httpport} is taken by another program; the server uses free "
                    "ports (see 'connect' in the answer)")
    up = mta_lua.start_server(timeout=timeout, port=p, httpport=hp, extra=list(_START_ORDER))
    return up, warn


def resource_states(bridge: Bridge) -> dict[str, str]:
    names = R.lua([R.CONTENT, R.LOGIC])
    code = (f"local out = {{}} for _, n in ipairs({names}) do local r = getResourceFromName(n) "
            "out[n] = r and getResourceState(r) or 'missing' end return out")
    vals = bridge.exec(code, "server")
    return vals[0] if vals and isinstance(vals[0], dict) else {}


def start_resources(bridge: Bridge, *, logic_changed: bool, content_changed: bool,
                    timeout: float = 20.0) -> dict[str, str]:
    """Make both resources run on the server; restart the ones whose files changed.

    Returns ``{resource: "started" | "restarted" | "running"}``. A content restart goes through
    ``td restart`` so the logic measures the time until the clients have the new models.
    """
    st = resource_states(bridge)
    if any(st.get(n) == "missing" for n in _START_ORDER):
        bridge.exec("refreshResources(false) return true", "server")
        deadline = time.monotonic() + timeout
        while any(st.get(n) == "missing" for n in _START_ORDER):
            if time.monotonic() > deadline:
                raise SatkError("NOT_READY", "the MTA server did not load the test resources",
                                hint="satk ingame logs --source server", data={"states": st})
            time.sleep(0.3)
            st = resource_states(bridge)
    done: dict[str, str] = {}
    for name in _START_ORDER:
        state = st.get(name)
        changed = logic_changed if name == R.LOGIC else content_changed
        if state != "running":
            bridge.exec(f"return startResource(getResourceFromName({R.lua(name)}), true)", "server")
            done[name] = "started"
        elif changed and name == R.CONTENT and st.get(R.LOGIC) == "running":
            bridge.server("restart", {})
            done[name] = "restarted"
        elif changed:
            bridge.exec(f"return restartResource(getResourceFromName({R.lua(name)}))", "server")
            done[name] = "restarted"
        else:
            done[name] = "running"
    deadline = time.monotonic() + timeout
    while True:
        time.sleep(0.3)
        st = resource_states(bridge)
        if all(st.get(n) == "running" for n in _START_ORDER):
            return done
        if time.monotonic() > deadline:
            raise SatkError("TIMEOUT", "the test resources did not start", hint="satk ingame logs --source scripts",
                            data={"states": st})


def wait_applied(bridge: Bridge, rev: str, timeout: float) -> dict[str, Any]:
    """Wait until every ready player reported ``rev``; ``{players, waited_s, timeout?}``."""
    t0 = time.monotonic()
    while True:
        try:
            st = bridge.server("status", {})
        except SatkError as e:
            if e.code != "NOT_READY" or time.monotonic() - t0 > timeout:
                raise
            time.sleep(0.25)  # the logic resource is (re)starting
            continue
        players = [p for p in (st.get("players") or []) if isinstance(p, dict)]
        if players and all(p.get("ready") and p.get("rev") == rev for p in players):
            return {"players": players, "waited_s": round(time.monotonic() - t0, 2)}
        if not players and time.monotonic() - t0 > 2.0:
            return {"players": [], "waited_s": round(time.monotonic() - t0, 2), "no_client": True}
        if time.monotonic() - t0 > timeout:
            return {"players": players, "waited_s": round(time.monotonic() - t0, 2), "timeout": True}
        time.sleep(0.25)


def log_marks() -> dict[str, int]:
    """Current sizes of the server and client log files (``ingame logs --since start`` reads after them)."""
    from .logs import log_files

    out = {}
    for src, p in log_files():
        try:
            out[f"{src}:{p.name}"] = p.stat().st_size
        except OSError:
            out[f"{src}:{p.name}"] = 0
    return out
